"""Public chat: one room per catalogue object plus a general room.

Nobody signs in. The browser generates a nickname from a fixed word list ("Stargazer-4821"), so
nobody can pick an offensive name, and the server only accepts nicknames of that shape. Messages
are short, filtered and kept for 24 hours; the server never stores who sent them (the client
address is only held in memory, for the anti-flood limit).

Filters, applied on the server (the frontend cannot be trusted):
- banned words in Spanish and English, also written with digits or symbols ("p3nd3jo", "f*ck"),
  with repeated letters ("puuuta") or spaced out ("p u t a");
- links, email addresses, social handles and phone numbers: no spam or phishing, and nobody
  shares personal data in a public room.
"""

from __future__ import annotations

import re
import threading
import time
import unicodedata

GENERAL_ROOM = "general"
MAX_LENGTH = 280
RETENTION_HOURS = 24
# Anti-flood: one message per client every this many seconds (in memory, per instance).
MIN_INTERVAL_S = 3.0
PAGE_SIZE = 50

# Keep in sync with NICKNAME_WORDS in frontend/lib/chat.ts.
NICKNAME_WORDS = (
    "Stargazer", "Comet", "Nebula", "Quasar", "Pulsar", "Photon", "Orbit", "Meteor",
    "Nova", "Galaxy", "Aurora", "Eclipse", "Zenith", "Voyager", "Cosmos", "Parsec",
)
NICKNAME_RE = re.compile(r"^(?P<word>[A-Z][a-z]+)-\d{4}$")
ROOM_RE = re.compile(r"^[a-z0-9-]{1,64}$")

# Matched against whole words after normalisation (see _variants): accents removed, digits and
# symbols read as letters. Written with their real spelling. Ordinary words that look rude out
# of context are left out on purpose ("cono": cone, "retrasado": delayed, "coger": to take).
BANNED_WORDS = frozenset(
    {
        # Spanish
        "puta", "puto", "putas", "putos", "pendejo", "pendeja", "pendejos", "pendejas",
        "cabron", "cabrona", "cabrones", "mierda", "verga", "vergas", "culero", "culera",
        "chingada", "chingado", "chingar", "chinga", "pinche", "joto", "jotos", "maricon",
        "maricones", "marica", "gilipollas", "zorra", "perra", "malparido", "malparida",
        "hijueputa", "hdp", "ctm", "conchetumare", "mamon", "mamona", "imbecil", "estupido",
        "estupida", "idiota", "subnormal", "sudaca", "follar", "polla", "violar", "violacion",
        "nazi", "nazis",
        # English
        "fuck", "fucker", "fucking", "fucked", "motherfucker", "shit", "shitty", "bullshit",
        "bitch", "bitches", "cunt", "cunts", "dick", "dicks", "cock", "cocks", "pussy", "whore",
        "slut", "bastard", "asshole", "faggot", "fag", "fags", "nigger", "niggers", "nigga",
        "niggas", "retard", "retarded", "rape", "rapist", "porn", "porno", "nude", "nudes",
        "kys", "wanker", "twat",
    }
)
# Stems caught inside longer words ("pendejazo", "fuckface"). Only stems that are never part of
# an ordinary word in Spanish or English.
BANNED_STEMS = ("fuck", "pendej", "cabron", "chingad", "hijueput", "nigger", "nigga", "faggot",
                "motherf", "bullshit")

_LEET = str.maketrans({"0": "o", "1": "i", "3": "e", "4": "a", "5": "s", "7": "t", "8": "b",
                       "@": "a", "$": "s", "!": "i", "|": "i"})

_URL_RE = re.compile(
    r"(https?://|www\.|\b[a-z0-9-]{2,}\.(com|net|org|io|co|me|ly|gg|xyz|app|dev|info|biz|es|mx"
    r"|ar|cl|pe|us|uk|ru|tk|link|site|online|shop|club|tv|ai|to|be|gl)\b|t\.me/|discord\.gg)",
    re.IGNORECASE,
)
_EMAIL_RE = re.compile(r"[\w.+-]+@[\w-]+\.[\w.-]+")
_HANDLE_RE = re.compile(r"(^|\s)@\w{3,}")
# Dates and times are common in an astronomy chat and must not read as phone numbers.
_DATE_TIME_RE = re.compile(r"\d{4}-\d{2}-\d{2}|\d{1,2}:\d{2}(:\d{2})?")
# 9 or more digits joined only by spaces, dashes or brackets (a decimal point means a number).
_PHONE_RE = re.compile(r"\+?\d(?:[\s\-()]{0,2}\d){8,}")


class ChatRejected(ValueError):
    """The message or nickname was refused; ``code`` says why, for the client."""

    def __init__(self, code: str, message: str) -> None:
        super().__init__(message)
        self.code = code


def valid_room(room: str) -> bool:
    return bool(ROOM_RE.match(room))


def check_nickname(nickname: str) -> str:
    match = NICKNAME_RE.match(nickname or "")
    if not match or match.group("word") not in NICKNAME_WORDS:
        raise ChatRejected("nickname", "Nicknames are generated by Nebo.")
    return nickname


def _clean(text: str) -> str:
    """Drop control and invisible characters, collapse whitespace."""
    kept = "".join(
        ch for ch in unicodedata.normalize("NFC", text)
        if ch == " " or unicodedata.category(ch)[0] not in ("C", "Z")
        or ch.isspace()
    )
    return re.sub(r"\s+", " ", kept).strip()


def _variants(word: str) -> set[str]:
    """The word as written, with stretched letters cut to two ("perrrra" -> "perra") and to one
    ("puuuta" -> "puta"). Banned entries keep their real spelling, so "pera" (pear) or "Niger"
    (the country) never match "perra" or the slur."""
    return {word, re.sub(r"(.)\1{2,}", r"\1\1", word), re.sub(r"(.)\1+", r"\1", word)}


def _words(text: str) -> set[str]:
    """Normalised words of ``text``, plus words spelled out with separators ("p u t a")."""
    plain = unicodedata.normalize("NFKD", text.lower())
    plain = "".join(ch for ch in plain if not unicodedata.combining(ch)).translate(_LEET)
    found = set(re.findall(r"[a-z]+", plain))
    # Letters separated by single spaces, dots, dashes, stars or underscores.
    for run in re.findall(r"(?:\b[a-z][\s.\-*_]){2,}[a-z]\b", plain):
        found.add(re.sub(r"[\s.\-*_]", "", run))
    # Dots or underscores inside a word ("p.uta", "mier_da").
    for joined in re.findall(r"[a-z]+(?:[._][a-z]+)+", plain):
        found.add(re.sub(r"[._]", "", joined))
    # A vowel hidden behind * or # ("f*ck", "p#ta"): try every vowel, up to two hidden letters.
    for masked in re.findall(r"[a-z]*[*#][a-z*#]*", plain):
        if 1 <= masked.count("*") + masked.count("#") <= 2 and re.search(r"[a-z]", masked):
            candidates = [""]
            for ch in masked:
                options = "aeiou" if ch in "*#" else ch
                candidates = [c + o for c in candidates for o in options]
            found.update(candidates)
    return {variant for word in found for variant in _variants(word)}


def has_banned_words(text: str) -> bool:
    words = _words(text)
    if words & BANNED_WORDS:
        return True
    return any(stem in word for word in words for stem in BANNED_STEMS)


def has_personal_data(text: str) -> str | None:
    """Which kind of link or personal data the text contains, or None."""
    if _EMAIL_RE.search(text):
        return "email addresses"
    if _URL_RE.search(text):
        return "links"
    if _HANDLE_RE.search(text):
        return "social media handles"
    if _PHONE_RE.search(_DATE_TIME_RE.sub(" ", text)):
        return "phone numbers"
    return None


def check_message(body: str) -> str:
    """The cleaned message, or ChatRejected with the reason."""
    text = _clean(body or "")
    if not text:
        raise ChatRejected("empty", "Write a message first.")
    if len(text) > MAX_LENGTH:
        raise ChatRejected("too_long", f"Messages are limited to {MAX_LENGTH} characters.")
    if has_banned_words(text):
        raise ChatRejected("blocked_words", "This message contains words that are not allowed.")
    found = has_personal_data(text)
    if found:
        raise ChatRejected(
            "personal_data", f"To keep everyone safe, {found} are not allowed in the public chat."
        )
    return text


class FloodGuard:
    """At most one message per client every ``interval_s`` seconds (per process)."""

    def __init__(self, interval_s: float = MIN_INTERVAL_S) -> None:
        self.interval_s = interval_s
        self._last: dict[str, float] = {}
        self._lock = threading.Lock()

    def wait_s(self, client: str) -> float:
        """0 when ``client`` may post now (and records it), else the seconds left."""
        now = time.monotonic()
        with self._lock:
            if len(self._last) > 10_000:  # Forget old entries so the map cannot grow forever.
                self._last = {k: t for k, t in self._last.items() if now - t < self.interval_s}
            last = self._last.get(client)
            if last is not None and now - last < self.interval_s:
                return self.interval_s - (now - last)
            self._last[client] = now
            return 0.0
